// Bakes an ANTI-ALIASED proportional font from a TTF into a C++ header, so the
// runtime needs no TTF/rasterizer. Each glyph stores 8-bit coverage (0..255) in a
// fixed 16 x CELL_H cell + an x-advance. The simulator shows the grayscale for
// smooth text; the firmware thresholds it to 1-bit for the e-paper panel.
//
//   c++ -std=c++17 -I/path/to/stb tools/genfont.cpp -o /tmp/genfont
//   /tmp/genfont <font.ttf> simulator/src/GeneratedFont.h [pixel_height]
#define STB_TRUETYPE_IMPLEMENTATION
#include "stb_truetype.h"

#include <cmath>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <vector>

int main(int argc, char** argv) {
    if (argc < 3) {
        std::fprintf(stderr, "usage: %s <font.ttf> <out.h> [pixel_height]\n", argv[0]);
        return 2;
    }
    const char* ttf_path = argv[1];
    const char* out_path = argv[2];
    const float px = argc > 3 ? static_cast<float>(std::atof(argv[3])) : 15.0f;
    const char* ns = argc > 4 ? argv[4] : "font"; // namespace sapiens::<ns>

    FILE* f = std::fopen(ttf_path, "rb");
    if (!f) { std::perror("open ttf"); return 1; }
    std::fseek(f, 0, SEEK_END);
    long sz = std::ftell(f);
    std::fseek(f, 0, SEEK_SET);
    std::vector<unsigned char> ttf(sz);
    if (std::fread(ttf.data(), 1, sz, f) != static_cast<size_t>(sz)) return 1;
    std::fclose(f);

    stbtt_fontinfo font;
    if (!stbtt_InitFont(&font, ttf.data(),
                        stbtt_GetFontOffsetForIndex(ttf.data(), 0))) {
        std::fprintf(stderr, "InitFont failed\n");
        return 1;
    }

    const float scale = stbtt_ScaleForPixelHeight(&font, px);
    int ascent, descent, line_gap;
    stbtt_GetFontVMetrics(&font, &ascent, &descent, &line_gap);
    const int baseline = static_cast<int>(std::lround(ascent * scale));
    const int CELL_H =
        static_cast<int>(std::lround((ascent - descent) * scale)) + 1;
    const int CELL_W = px > 16.0f ? static_cast<int>(std::lround(px)) + 2 : 16;
    const int FIRST = 32, LAST = 126;

    FILE* o = std::fopen(out_path, "wb");
    if (!o) { std::perror("open out"); return 1; }
    std::fprintf(o,
        "#pragma once\n"
        "// AUTO-GENERATED by tools/genfont.cpp from %s at %.0fpx. Do not edit.\n"
        "// 8-bit anti-aliased coverage; 0=blank, 255=full ink.\n"
        "#include <cstdint>\n\n"
        "namespace sapiens::%s {\n\n"
        "constexpr int CELL_H = %d;\n"
        "constexpr int CELL_W = %d;\n"
        "constexpr int FIRST = %d;\n"
        "constexpr int LAST = %d;\n\n"
        "struct Glyph { std::uint8_t advance; std::uint8_t cov[CELL_H * CELL_W]; };\n\n"
        "inline constexpr Glyph GLYPHS[] = {\n",
        ttf_path, px, ns, CELL_H, CELL_W, FIRST, LAST);

    for (int c = FIRST; c <= LAST; ++c) {
        int adv = 0, lsb = 0;
        stbtt_GetCodepointHMetrics(&font, c, &adv, &lsb);
        const int advance = static_cast<int>(std::lround(adv * scale));

        int w = 0, h = 0, xoff = 0, yoff = 0;
        unsigned char* bmp =
            stbtt_GetCodepointBitmap(&font, scale, scale, c, &w, &h, &xoff, &yoff);

        std::vector<uint8_t> cov(CELL_H * CELL_W, 0);
        for (int gy = 0; gy < h; ++gy) {
            const int cy = baseline + yoff + gy;
            if (cy < 0 || cy >= CELL_H) continue;
            for (int gx = 0; gx < w; ++gx) {
                const int cx = xoff + gx;
                if (cx < 0 || cx >= CELL_W) continue;
                cov[cy * CELL_W + cx] = bmp[gy * w + gx];
            }
        }
        if (bmp) stbtt_FreeBitmap(bmp, nullptr);

        std::fprintf(o, "  {%d, {", advance);
        for (size_t i = 0; i < cov.size(); ++i)
            std::fprintf(o, "%d%s", cov[i], i + 1 < cov.size() ? "," : "");
        std::fprintf(o, "}}, // '%c' (%d)\n", (c >= 32 && c < 127) ? c : '?', c);
    }

    std::fprintf(o,
        "};\n\n"
        "inline const Glyph& glyph(unsigned char c) {\n"
        "    if (c < FIRST || c > LAST) c = ' ';\n"
        "    return GLYPHS[c - FIRST];\n"
        "}\n"
        "constexpr int line_height() { return CELL_H; }\n\n"
        "} // namespace\n");
    std::fclose(o);
    std::fprintf(stderr, "wrote %s: cell=%dx%d baseline=%d glyphs=%d\n", out_path,
                 CELL_W, CELL_H, baseline, LAST - FIRST + 1);
    return 0;
}
