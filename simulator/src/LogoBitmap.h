// Call plot(x,y) for every ink pixel (0<=x<W, 0<=y<H).
template <class Plot>
inline void draw(Plot plot) {
    for (int y = 0; y < H; ++y)
        for (int x = 0; x < W; ++x)
            if (BITS[y * STRIDE + (x >> 3)] & (0x80u >> (x & 7))) plot(x, y);
}

